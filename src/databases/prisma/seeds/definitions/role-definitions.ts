export interface RoleSeedDefinition {
    roleId: string;
    name: string;
    displayName: string;
    description: string;
    isSystemRole: boolean;
    isActive: boolean;
    permissionIds: string[];
}

const defineRole = (
    roleId: string,
    displayName: string,
    description: string,
    permissionIds: string[],
    options: Partial<Pick<RoleSeedDefinition, "name" | "isSystemRole" | "isActive">> = {},
): RoleSeedDefinition => {
    const deduplicatedPermissionIds = [...new Set(permissionIds)];
    assertValidPermissionIds(deduplicatedPermissionIds, `role ${roleId}`);

    return {
        roleId,
        name: options.name ?? roleId.replace(/-/g, "_"),
        displayName,
        description,
        isSystemRole: options.isSystemRole ?? true,
        isActive: options.isActive ?? true,
        permissionIds: deduplicatedPermissionIds,
    };
};

